// Builds lessons.gen.ts and patterns.gen.ts, the lesson and pattern payloads the mock server of this feature replays, from the
// mini dataset (packages/testkit/mini). Run from the repository root after the dataset changes:
//   node apps/web/src/features/cases/mock-data/build.mjs
// Forms, endings, triggers, lessons and exercises are copied as they are; nothing is invented.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const mini = join(here, '../../../../../../packages/testkit/mini');
const read = (file) =>
  readFileSync(join(mini, file), 'utf8')
    .split('\n')
    .filter((l) => l.trim() !== '')
    .map((l) => JSON.parse(l));

const CASE_DIGIT = { nom: '1', gen: '2', dat: '3', acc: '4', voc: '5', loc: '6', ins: '7' };
const CASE_NAME = {
  nom: 'nominative',
  gen: 'genitive',
  dat: 'dative',
  acc: 'accusative',
  voc: 'vocative',
  loc: 'locative',
  ins: 'instrumental',
};
const MASCULINE = new Set(['m_anim', 'm_inan']);

const lessons = read('lessons.jsonl');
const triggers = new Map(read('triggers.jsonl').map((t) => [t.id, t]));
const patterns = new Map(read('patterns.jsonl').map((p) => [p.id, p]));
const exercises = new Map(read('exercises.jsonl').map((e) => [e.id, e]));
const forms = read('forms.jsonl');
const lemmas = read('lemmas.jsonl');

function formMap(lemmaId) {
  const map = {};
  for (const f of forms) {
    if (f.lemmaId !== lemmaId || f.tags === '') continue;
    const key = f.form.toLowerCase().normalize('NFC');
    map[key] = [...new Set([...(map[key] ?? []), ...f.tags.split(' ')])];
  }
  return map;
}

/** The ending every other pattern of the same gender family has for the expected tag. */
function siblingEndings(ex) {
  const own = patterns.get(ex.pattern);
  if (own?.pos !== 'noun') return undefined;
  const tag = `${ex.number === 'sg' ? 's' : 'p'}${CASE_DIGIT[ex.case]}`;
  const family = (g) => (MASCULINE.has(g) ? 'm' : g);
  const out = {};
  for (const p of patterns.values()) {
    if (p.pos !== 'noun' || family(p.gender) !== family(own.gender)) continue;
    if (p.endings[tag] !== undefined) out[p.id] = p.endings[tag];
  }
  return Object.keys(out).length > 1 ? out : undefined;
}

function triggerRow(id) {
  const t = triggers.get(id);
  return {
    id: t.id,
    kind: t.kind,
    lemma: t.lemma,
    lemmaId: t.lemmaId ?? null,
    case: t.case,
    meaningEn: t.meaningEn,
    noteEn: t.noteEn ?? null,
    exampleSk: t.exampleSk,
    exampleEn: t.exampleEn,
    contrastGroup: t.contrastGroup ?? null,
  };
}

function item(id) {
  const ex = exercises.get(id);
  const t = ex.triggerId ? triggers.get(ex.triggerId) : undefined;
  const lemmaIds = ex.target.lemmaIds;
  const sib = siblingEndings(ex);
  return {
    exerciseId: ex.id,
    kind: ex.kind,
    sentenceSk: ex.sentenceSk,
    sentenceEn: ex.sentenceEn,
    blank: { start: ex.target.start, end: ex.target.end },
    cue: ex.target.cue,
    answers: ex.target.answers,
    ...(ex.options ? { options: ex.options } : {}),
    features: {
      case: ex.case,
      number: ex.number,
      gender: ex.gender,
      ...(ex.pattern ? { pattern: ex.pattern } : {}),
    },
    ...(t
      ? { trigger: { id: t.id, kind: t.kind, label: `${t.lemma} + ${CASE_NAME[t.case]}` } }
      : {}),
    // A phrase answer ('novú prácu'): the table of the noun, the last word.
    formMap: formMap(lemmaIds[lemmaIds.length - 1]),
    ...(sib ? { siblingEndings: sib } : {}),
  };
}

const out = {};
for (const l of lessons) {
  const triggerIds = new Set();
  const steps = l.steps.map((s) => {
    const content = s.content;
    if (content.kind === 'triggers') for (const id of content.triggerIds) triggerIds.add(id);
    const exs = 'exerciseIds' in content ? content.exerciseIds.map(item) : [];
    return { ord: s.ord, content, exercises: exs };
  });
  out[l.id] = {
    lesson: {
      id: l.id,
      ord: l.ord,
      titleEn: l.titleEn,
      titleSk: l.titleSk,
      case: l.case ?? null,
      number: l.number ?? null,
      focus: l.focus,
      summaryMd: l.summaryMd,
      prerequisites: l.prerequisites ?? [],
    },
    steps,
    triggers: [...triggerIds].map(triggerRow),
    progress: null,
  };
}

const HEADER =
  '// Generated by build.mjs from the mini dataset (packages/testkit/mini). Do not edit.\n';
writeFileSync(
  join(here, 'lessons.gen.ts'),
  `${HEADER}import type { LessonDetail } from '@app/contracts';\n\nexport const DATASET_LESSONS: Record<string, LessonDetail> = ${JSON.stringify(out, null, 1)};\n`,
);

// Pattern tables: the model word, and as the everyday word the most frequent other lemma of the
// same pattern in the set (none when the set has no other).
const patternOut = {};
for (const p of patterns.values()) {
  const model = lemmas.find((l) => l.id === p.modelLemmaId);
  const everyday = lemmas
    .filter((l) => l.pattern === p.id && l.id !== p.modelLemmaId)
    .sort((a, b) => a.freqRank - b.freqRank)[0];
  patternOut[p.id] = {
    id: p.id,
    labelSk: p.labelSk,
    pos: p.pos,
    gender: p.gender ?? null,
    model: model ? { lemmaId: model.id, lemma: model.lemma } : null,
    everydayModel: everyday ? { lemmaId: everyday.id, lemma: everyday.lemma } : null,
    endings: p.endings,
    notesEn: p.notesEn ?? null,
  };
}
writeFileSync(
  join(here, 'patterns.gen.ts'),
  `${HEADER}import type { PatternDetail } from '@app/contracts';\n\nexport const DATASET_PATTERNS: Record<string, PatternDetail> = ${JSON.stringify(patternOut, null, 1)};\n`,
);
console.log(`wrote ${Object.keys(out).length} lessons, ${Object.keys(patternOut).length} patterns`);
