// `pnpm --filter @app/db sql:bundle [content folder] > setup.sql`
// Writes one SQL script for a fresh Supabase project, to paste into its SQL editor:
// every migration, drizzle's record of them (so `db:migrate` later skips them), and the
// content of a folder (default: the mini dataset) as plain inserts. The content is loaded
// into a throwaway PGlite database first, so the inserts are exactly what loadContent writes.
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createDb, loadContent, MIGRATIONS_FOLDER, migrate } from '../src/index';

const REPO = fileURLToPath(new URL('../../..', import.meta.url));
const DEFAULT_CONTENT = resolve(REPO, 'packages/testkit/mini');

interface JournalEntry {
  idx: number;
  when: number;
  tag: string;
}

function quote(text: string): string {
  return `'${text.replaceAll("'", "''")}'`;
}

function migrationsSql(): string {
  const journal = JSON.parse(
    readFileSync(join(MIGRATIONS_FOLDER, 'meta/_journal.json'), 'utf8'),
  ) as { entries: JournalEntry[] };
  const parts: string[] = [];
  const records: string[] = [];
  for (const e of journal.entries) {
    const text = readFileSync(join(MIGRATIONS_FOLDER, `${e.tag}.sql`), 'utf8');
    const statements = text
      .split('--> statement-breakpoint')
      .map((s) => s.trim())
      .filter((s) => s.length > 0);
    parts.push(
      `-- Migration ${e.tag}\n${statements.map((s) => (s.endsWith(';') ? s : `${s};`)).join('\n')}`,
    );
    // drizzle hashes the whole file and orders by the journal's `when`.
    const hash = createHash('sha256').update(text).digest('hex');
    records.push(`(${quote(hash)}, ${e.when})`);
  }
  parts.push(`-- drizzle's record of the migrations above, so a later \`db:migrate\` skips them.
CREATE SCHEMA IF NOT EXISTS drizzle;
CREATE TABLE IF NOT EXISTS drizzle.__drizzle_migrations (
  id SERIAL PRIMARY KEY,
  hash text NOT NULL,
  created_at bigint
);
INSERT INTO drizzle.__drizzle_migrations (hash, created_at) VALUES
  ${records.join(',\n  ')};`);
  return parts.join('\n\n');
}

async function contentSql(folder: string): Promise<{ sql: string; version: string }> {
  const database = createDb({ mode: 'pglite' });
  try {
    await migrate(database);
    const r = await loadContent(database, folder);
    const pglite = database.pglite;
    if (!pglite) throw new Error('expected a PGlite database');
    const q = async <T>(text: string): Promise<T[]> => (await pglite.query<T>(text)).rows;
    // Tables of schema ling in foreign key order (parents first).
    const tables = await q<{ name: string }>(`
      WITH RECURSIVE t AS (
        SELECT c.oid, c.relname::text AS name FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'ling' AND c.relkind = 'r'
      ), dep AS (
        SELECT t.oid, t.name, 0 AS depth FROM t
        UNION ALL
        SELECT t.oid, t.name, dep.depth + 1 FROM t
        JOIN pg_constraint k ON k.conrelid = t.oid AND k.contype = 'f' AND k.confrelid <> t.oid
        JOIN dep ON dep.oid = k.confrelid
      )
      SELECT name FROM dep GROUP BY name ORDER BY max(depth), name`);
    const out: string[] = [];
    for (const { name } of tables) {
      const cols = await q<{ column_name: string; identity: string }>(`
        SELECT column_name, is_identity AS identity FROM information_schema.columns
        WHERE table_schema = 'ling' AND table_name = ${quote(name)} AND is_generated = 'NEVER'
        ORDER BY ordinal_position`);
      const list = cols.map((c) => `"${c.column_name}"`).join(', ');
      const rows = await q<{ j: unknown }>(
        `SELECT coalesce(jsonb_agg(to_jsonb(x)), '[]'::jsonb) AS j FROM ling."${name}" x`,
      );
      const json = JSON.stringify(rows[0]?.j ?? []);
      if (json === '[]') continue;
      const overriding = cols.some((c) => c.identity === 'YES') ? ' OVERRIDING SYSTEM VALUE' : '';
      out.push(
        `INSERT INTO ling."${name}" (${list})${overriding}\nSELECT ${list} FROM jsonb_populate_recordset(NULL::ling."${name}", ${quote(json)}::jsonb);`,
      );
      if (overriding)
        out.push(
          `SELECT setval(pg_get_serial_sequence('ling."${name}"', 'id'), (SELECT max(id) FROM ling."${name}"));`,
        );
    }
    return { sql: out.join('\n\n'), version: r.version };
  } finally {
    await database.close();
  }
}

async function main(): Promise<void> {
  const folder = resolve(process.env.INIT_CWD ?? process.cwd(), process.argv[2] ?? DEFAULT_CONTENT);
  const content = await contentSql(folder);
  process.stdout.write(`-- Database setup for a fresh Supabase project. Generated by
-- \`pnpm --filter @app/db sql:bundle\`; do not edit by hand.
-- Paste the whole file into the Supabase SQL editor and press Run. It runs as one
-- transaction: if any statement fails, nothing is changed.
-- Content: ${content.version}

BEGIN;

${migrationsSql()}

-- Content (${content.version})
${content.sql}

COMMIT;
`);
}

main().catch((e: unknown) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
